logger = logging.getLogger("EmailService")

SENT_LOG_FILE = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(__file__))), "data", "sent_emails.json"
)

def log_dispatched_email(entry: dict):
    os.makedirs(os.path.dirname(SENT_LOG_FILE), exist_ok=True)
    with file_lock(SENT_LOG_FILE):
        logs = []
        if os.path.exists(SENT_LOG_FILE):
            try:
                with open(SENT_LOG_FILE, "r", encoding="utf-8") as f:
                    logs = json.load(f)
            except Exception:
                logs = []
        logs.append(entry)
        atomic_write_json(SENT_LOG_FILE, logs)

def format_daily_digest(jobs: List[JobPosting], min_score: int = 70) -> Dict[str, str]:
    """Formats an HTML and plain-text daily job digest for high-match roles."""
    high_match = [j for j in jobs if j.match_score >= min_score]
    high_match.sort(key=lambda x: x.match_score, reverse=True)

    today_str = datetime.utcnow().strftime("%B %d, %Y")
    subject = f"🎯 Daily Job Digest: {len(high_match)} Senior Tech Roles for Anser Nawaz ({today_str})"

    # Plain text version
    text_lines = [
        f"Daily Senior Tech Job Digest for Anser Nawaz - {today_str}",
        f"Found {len(high_match)} roles with match score >= {min_score}%\n",
        "=" * 60
    ]

    for idx, job in enumerate(high_match[:15], 1):
        text_lines.append(f"{idx}. [{job.match_score}% Match] {job.title} at {job.company}")
        text_lines.append(f"   • Location: {job.location}")
        text_lines.append(f"   • Category: {job.category} | Source: {job.source}")
        text_lines.append(f"   • Salary:   {job.salary}")
        text_lines.append(f"   • Apply:    {job.url}")
        text_lines.append("-" * 60)

    # HTML version
    job_cards_html = ""
    for job in high_match[:15]:
        score_color = "#10b981" if job.match_score >= 80 else "#3b82f6"
        job_cards_html += f"""
        <div style="border: 1px solid #e5e7eb; border-radius: 8px; padding: 16px; margin-bottom: 12px; background-color: #ffffff;">
            <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 8px;">
                <span style="background-color: {score_color}; color: #ffffff; padding: 4px 10px; border-radius: 9999px; font-size: 12px; font-weight: bold;">
                    {job.match_score}% Match
                </span>
                <span style="font-size: 12px; color: #6b7280; font-weight: 500;">
                    {job.source} • {job.category}
                </span>
            </div>
            <h3 style="margin: 0 0 4px 0; color: #111827; font-size: 16px; font-weight: bold;">{job.title}</h3>
            <p style="margin: 0 0 8px 0; color: #4b5563; font-size: 14px; font-weight: 500;">{job.company} — 📍 {job.location}</p>
            <p style="margin: 0 0 12px 0; color: #059669; font-size: 13px; font-weight: 600;">💳 {job.salary}</p>
            <a href="{job.url}" style="display: inline-block; background-color: #111827; color: #ffffff; padding: 6px 14px; text-decoration: none; border-radius: 6px; font-size: 13px; font-weight: 600;">
                Review & Apply &rarr;
            </a>
        </div>
        """

    html_body = f"""
    <html>
    <body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #f9fafb; padding: 24px;">
        <div style="max-width: 640px; margin: 0 auto; background-color: #ffffff; border-radius: 12px; border: 1px solid #e5e7eb; padding: 24px;">
            <h1 style="color: #111827; font-size: 22px; margin-top: 0;">🎯 Senior Tech Job Digest</h1>
            <p style="color: #4b5563; font-size: 14px;">
                Curated high-match opportunities for <strong>Anser Nawaz</strong> (Senior Full-Stack & Mobile Engineer) in Lahore, Pakistan and International Remote.
            </p>
            <div style="margin-top: 20px;">
                {job_cards_html}
            </div>
            <p style="color: #9ca3af; font-size: 12px; margin-top: 24px; text-align: center;">
                Generated by Job Discovery Gateway • All credentials and data secured locally.
            </p>
        </div>
    </body>
    </html>
    """

    return {
        "subject": subject,
        "text": "\n".join(text_lines),
        "html": html_body,
        "count": len(high_match)
    }

async def send_application_email_with_approval(
    tracker_id: str,
    recipient_email: str,
    subject: str,
    body_text: str,
    approved: bool
) -> Dict[str, Any]:
    """
    Sends an application or recruiter outreach email ONLY after explicit user approval.
    If SMTP credentials are not set, logs the action safely in dry-run mode.
    """
    if not approved:
        raise ValueError("Security Gate: Explicit user approval is required before sending application emails.")

    if not recipient_email or "@" not in recipient_email:
        raise ValueError("Invalid recipient email address.")

    smtp_host = os.getenv("SMTP_HOST")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    smtp_user = (os.getenv("SMTP_USER") or "").strip()
    smtp_pass = (os.getenv("SMTP_PASS") or "").replace(" ", "").strip()
    active_prof = None
    if tracker_id:
        existing_item = TRACKER_STORE.get_application(tracker_id)
        if existing_item and existing_item.candidate_id:
            from app.storage.profile_store import PROFILE_STORE
            cand_prof = PROFILE_STORE.get_profile(existing_item.candidate_id)
            if cand_prof and cand_prof.email:
                active_prof = cand_prof
    sender_email = (
        os.getenv("SENDER_EMAIL")
        or os.getenv("CANDIDATE_EMAIL")
        or (active_prof.email if active_prof else None)
        or smtp_user
        or ANSER_PROFILE.email
    )
    sender_name = (
        os.getenv("SENDER_NAME")
        or os.getenv("CANDIDATE_NAME")
        or (active_prof.name if active_prof else None)
        or ANSER_PROFILE.name
    )

    dispatch_entry = {
        "tracker_id": tracker_id,
        "sender": formataddr((sender_name, sender_email)) if sender_name else sender_email,
        "recipient": recipient_email,
        "subject": subject,
        "body_snippet": body_text[:200],
        "timestamp": datetime.utcnow().isoformat(),
        "approved": approved,
    }

    if not smtp_host or not smtp_user or not smtp_pass:
        # Dry-run / Safe Simulation Mode
        dispatch_entry["mode"] = "simulated_dry_run"
        dispatch_entry["status"] = "logged_successfully"
        log_dispatched_email(dispatch_entry)

        # In dry-run: email was NOT sent and application was NOT submitted to employer.
        # Keep email_sent = False, do NOT change application stage to applied.
        app_item = TRACKER_STORE.get_application(tracker_id)
        if app_item:
            app_item.email_approved = True
            app_item.email_sent = False
            app_item.recruiter_email_sent = False
            app_item.email_dispatch_mode = "simulated_dry_run"
            app_item.email_recipient = recipient_email

            notice = "[Dry-run logged — not transmitted]"
            existing_notes = app_item.notes or ""
            if notice not in existing_notes:
                app_item.notes = f"{existing_notes}\n{notice}".strip() if existing_notes else notice
            TRACKER_STORE.save_or_update(app_item, expected_candidate_id=app_item.candidate_id)

        logger.info(f"Email to {recipient_email} approved and logged in dry-run mode (not transmitted).")
        return {
            "status": "simulated",
            "message": "Approval verified. Dry-run logged — not transmitted (configure SMTP_HOST/USER in .env to transmit live).",
            "dispatch_id": tracker_id,
            "email_sent": False
        }

    # Live SMTP Dispatch
    try:
        msg = MIMEMultipart()
        msg["From"] = formataddr((sender_name, sender_email)) if sender_name else sender_email
        msg["Reply-To"] = sender_email
        msg["To"] = recipient_email
        msg["Subject"] = subject
        msg.attach(MIMEText(body_text, "plain"))

        # Automatically attach Anser Nawaz's verified PDF Resume if available
        resume_attached = False
        resume_path = os.path.join(
            os.path.dirname(os.path.dirname(os.path.dirname(__file__))), "data", "Anser_Nawaz_Resume.pdf"
        )
        if os.path.exists(resume_path):
            try:
                with open(resume_path, "rb") as f:
                    pdf_part = MIMEApplication(f.read(), _subtype="pdf")
                    pdf_part.add_header(
                        "Content-Disposition",
                        "attachment",
                        filename="Anser_Nawaz_Resume.pdf"
                    )
                    msg.attach(pdf_part)
                    resume_attached = True
                    logger.info("Attached Anser_Nawaz_Resume.pdf to outgoing email.")
            except Exception as attach_err:
                logger.warning(f"Failed to attach resume PDF: {attach_err}")

        if smtp_port == 465:
            with smtplib.SMTP_SSL(smtp_host, smtp_port) as server:
                server.login(smtp_user, smtp_pass)
                server.send_message(msg)
        else:
            with smtplib.SMTP(smtp_host, smtp_port) as server:
                server.starttls()
                server.login(smtp_user, smtp_pass)
                server.send_message(msg)

        dispatch_entry["mode"] = "live_smtp"
        dispatch_entry["status"] = "sent_successfully"
        dispatch_entry["resume_attached"] = resume_attached
        log_dispatched_email(dispatch_entry)

        # Live transmission succeeded
        app_item = TRACKER_STORE.get_application(tracker_id)
        if app_item:
            app_item.status = "applied"
            if hasattr(app_item, "job") and app_item.job:
                app_item.job.application_status = "applied"
            app_item.email_approved = True
            app_item.email_sent = True
            app_item.recruiter_email_sent = True
            app_item.email_dispatch_mode = "live_smtp"
            app_item.email_recipient = recipient_email
            
            notice = f"[Live recruiter email transmitted to {recipient_email}]"
            existing_notes = app_item.notes or ""
            if notice not in existing_notes:
                app_item.notes = f"{existing_notes}\n{notice}".strip() if existing_notes else notice
            TRACKER_STORE.save_or_update(app_item, expected_candidate_id=app_item.candidate_id)

        return {
            "status": "sent",
            "message": f"Application outreach email successfully transmitted to {recipient_email}.",
            "dispatch_id": tracker_id,
            "email_sent": True
        }
    except Exception as err:
        logger.error(f"Live SMTP dispatch error: {err}")
        dispatch_entry["mode"] = "live_smtp"
        dispatch_entry["status"] = f"error: {str(err)}"
        log_dispatched_email(dispatch_entry)
        raise RuntimeError(f"SMTP transmission failed: {str(err)}")
